"""Copy distinct architectural GLBs from the user's model collections for the gallery."""

import json
import shutil
from pathlib import Path


home = Path.home()
models = home / "Documents/Models"
examples = Path(__file__).resolve().parents[1]
target = examples / "public/models/building-catalog"
manifest = examples / "src/buildingCatalog.ts"

# Alternate exports and non-building props (roads, trees, cars, lights, floors) are omitted.
entries = [
    ("园区主楼", models / "SmartPark园区/p6cb41dtty_1698736416127_vk82wl5uyc.glb", "park-buildings.glb", "主楼", "Models · 园区"),
    ("园区小楼", models / "SmartPark园区/p6cb41dtty_1698736416127_vk82wl5uyc.glb", "park-buildings.glb", "小楼", "Models · 园区"),
    ("工业建筑 01", models / "IntelligentIndustrialPark智慧工业园区/models/gjtbv1cfm_1662089773592_uf6oy9tsg.glb", "industrial-01.glb", None, "Models · 工业园区"),
    ("工业建筑 02", models / "IntelligentIndustrialPark智慧工业园区/models/iwt1ei4nia_1662089796712_tc9janrwvr.glb", "industrial-02.glb", None, "Models · 工业园区"),
    ("工业建筑 03", models / "IntelligentIndustrialPark智慧工业园区/models/qtlrilkzt5_1662090699430_r3vh538j4.glb", "industrial-03.glb", None, "Models · 工业园区"),
    ("商圈一号楼", models / "智慧商圈综合体安保可视化/uw4z5rdjb8_1703656794983_wj3nt5ltw.glb", "shopping-building.glb", None, "Models · 商圈"),
    ("园区配套建筑", models / "SmartPark智慧园区/1664262746976_68254592_其他房子.glb", "park-other-buildings.glb", "SM_HZZX_JZ", "Models · 智慧园区"),
]

target.mkdir(parents=True, exist_ok=True)
selected_files = {filename for _, _, filename, _, _ in entries}
for stale in target.glob('*.glb'):
    if stale.name not in selected_files:
        stale.unlink()
catalog = []
for name, source, filename, node, group in entries:
    if not source.is_file():
        raise FileNotFoundError(source)
    destination = target / filename
    if not destination.exists() or destination.stat().st_size != source.stat().st_size:
        shutil.copy2(source, destination)
    catalog.append({
        "name": name,
        "file": f"/models/building-catalog/{filename}",
        "bytes": source.stat().st_size,
        "group": group,
        **({"node": node} if node else {}),
    })

manifest.write_text(
    "// Generated by scripts/import-building-catalog.py.\n"
    + "export default " + json.dumps(catalog, ensure_ascii=False, indent=2) + " as const;\n",
    encoding="utf-8",
)
print(f"Imported {len(catalog)} building previews from {len(set(x[2] for x in entries))} GLBs")
